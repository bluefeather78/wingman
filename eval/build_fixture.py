#!/usr/bin/env python3
"""Turn any adjudicated scrape batch into a grading fixture, automatically. FREE (DB read only).

This closes the compounding loop:

    scrape  ->  review (verdicts + reason codes land in the catalog)  ->  build_fixture.py
            ->  a frozen fixture grade_scraper_batch.py replays  ->  no future pipeline change
                can silently lose an approved row  ->  next scrape

Ground truth grows with every review session at zero manual effort. It reads the `inserted` ids
from one or more scrape_review_*.json snapshots, looks up each row's CURRENT moderation_status +
moderation_reason in the live catalog, and writes a fixture in the exact shape
scraper_grading_20260823.json uses. Un-reviewed (pending) rows are excluded — they are not ground
truth yet.

    python build_fixture.py --batch scraper-national-20260823 \
        --snapshot scrape_review_national_20260823-012518.json \
                   scrape_review_national_20260823-015749.json \
        --out tests/fixtures/scraper_grading_20260823_regen.json
"""
import argparse
import datetime
import json
import os

import sys
# This script lives under eval/ but imports the repo-root shared
# libraries (supabase_common) by bare name, the way every
# root script does. Running it as `python eval/build_fixture.py` puts its OWN directory on
# sys.path, not the repo root, so the root has to be added explicitly.
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from supabase_common import load_dotenv, supabase_get

REPO = os.path.dirname(os.path.abspath(__file__))
# moderation_status -> fixture verdict. All three negatives grade identically; the hand-built
# 08-23 fixture used "deleted" for the 7 rows an operator SQL-deleted before tombstones existed.
STATUS_TO_VERDICT = {"approved": "approved", "rejected": "rejected", "duplicate": "duplicate"}


def _snapshot_ids(paths):
    """{id: name} from the `inserted` rows of the given snapshots (tolerates both shapes)."""
    out = {}
    for p in paths:
        full = p if os.path.isabs(p) else os.path.join(REPO, p)
        with open(full, encoding="utf-8") as f:
            data = json.load(f)
        entries = data.get("inserted", []) if isinstance(data, dict) else data
        for r in entries or []:
            if isinstance(r, dict) and r.get("id"):
                out[r["id"]] = r.get("name")
    return out


def _chunks(seq, n):
    for i in range(0, len(seq), n):
        yield seq[i:i + n]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--batch", required=True, help="Batch label, e.g. scraper-national-20260823.")
    ap.add_argument("--snapshot", nargs="+", required=True, help="scrape_review_*.json file(s).")
    ap.add_argument("--out", required=True, help="Fixture path to write.")
    args = ap.parse_args()

    load_dotenv()
    url = os.environ.get("SUPABASE_URL", "").rstrip("/")
    key = os.environ.get("SUPABASE_SERVICE_KEY") or os.environ.get("SUPABASE_ANON_KEY")
    if not url or not key:
        print("[ERROR] SUPABASE_URL and a key must be set in .env.")
        raise SystemExit(1)

    ids_names = _snapshot_ids(args.snapshot)
    print(f"[OK] {len(ids_names)} inserted row id(s) across {len(args.snapshot)} snapshot(s).")

    verdicts, pending, missing = {}, 0, 0
    seen = set()
    for chunk in _chunks(list(ids_names), 100):
        rows = supabase_get(url, "opportunities",
                            {"select": "id,name,moderation_status,moderation_reason",
                             "id": f"in.({','.join(chunk)})"}, key) or []
        for r in rows:
            seen.add(r["id"])
            verdict = STATUS_TO_VERDICT.get(r.get("moderation_status"))
            if not verdict:
                pending += 1
                continue
            entry = {"verdict": verdict, "name": r.get("name") or ids_names.get(r["id"])}
            if r.get("moderation_reason"):
                entry["reason"] = r["moderation_reason"]
            verdicts[r["id"]] = entry
    missing = len(ids_names) - len(seen)

    counts = {}
    for e in verdicts.values():
        counts[e["verdict"]] = counts.get(e["verdict"], 0) + 1
    fixture = {
        "batch": args.batch,
        "snapshots": [os.path.basename(p) for p in args.snapshot],
        "graded_at": datetime.date.today().isoformat(),
        "grading": "Auto-generated by build_fixture.py from live moderation verdicts.",
        "verdicts": verdicts,
    }
    out = args.out if os.path.isabs(args.out) else os.path.join(REPO, args.out)
    with open(out, "w", encoding="utf-8") as f:
        json.dump(fixture, f, indent=1, ensure_ascii=False)
    print(f"[OK] Wrote {out}: {len(verdicts)} verdict(s) {counts}; "
          f"{pending} still pending (excluded), {missing} id(s) not found in catalog.")


if __name__ == "__main__":
    main()
